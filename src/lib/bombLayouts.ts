// 판 크기에 맞는 배치를 전체 크기 글자 지도로 펼친다(테두리 포함). 없으면 null(옛 격자 사용).
export function layoutFor(map: MapId, cols: number, rows: number): string[] | null {
  const tpl = cols === 17 && rows === 13 ? SMALL[map] : cols === 21 && rows === 15 ? BIG[map] : null
  if (!tpl) return null
  const iw = cols - 2
  const half = (iw + 1) / 2
  const out: string[] = []
  out.push('#'.repeat(cols))
  for (let y = 0; y < rows - 2; y++) {
    const row = tpl[y]
    if (!row || row.length !== half) throw new Error(`bad layout ${map} ${cols}x${rows} row ${y}`)
    let line = '#'
    for (let x = 0; x < iw; x++) line += x < half ? row[x] : row[iw - 1 - x]
    out.push(line + '#')
  }
  out.push('#'.repeat(cols))
  return out
}
